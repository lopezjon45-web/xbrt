#!/usr/bin/env python3
"""Writes core/gen/kernel_exports.inc, the xboxkrnl ordinal -> export name table, from ghidra-xbe's XbeLoader.java.

    gen-kernel-exports.py <XbeLoader.java> <out .inc>
"""
import re
import sys


def main(java_path, out_path):
    src = open(java_path, encoding="utf-8").read()
    table = src[src.index("kernelExports = {"):]
    table = table[:table.index("};")]
    names = {int(n): name for name, n in re.findall(r'"(\w*)",\s*//\s*(\d+)', table)}
    top = max(names)
    assert top >= 366, f"only {top} ordinals in {java_path}"
    with open(out_path, "w") as f:
        f.write("// Generated by scripts/gen-kernel-exports.py from ghidra-xbe's XbeLoader.java. Index = ordinal; \"\" = none.\n")
        f.write(f"inline constexpr std::string_view kKernelExports[{top + 1}] = {{\n")
        for o in range(top + 1):
            f.write(f'    "{names.get(o, "")}",   // {o}\n')
        f.write("};\n")
    print(f"{out_path}: {len([n for n in names.values() if n])} names, ordinals 0..{top}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
